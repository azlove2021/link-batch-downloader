#!/usr/bin/env node
/* ============================================================================
 * 文本处理 · 纯函数单元测试（脱敏 / 粘贴清洗）
 *
 * 脱敏最怕两件事：该打的没打（泄露）、不该打的打了（误伤订单号/长数字）。
 * 清洗最怕把不该拼的行拼在一起。所以这里全是边界用例。
 *
 * 运行： npm test（会连同一致性校验一起跑）
 * ==========================================================================*/
'use strict';

const path = require('path');

/* 让浏览器风格的 IIFE 能在 Node 里加载 */
global.window = global;
require(path.join(__dirname, '..', 'js', 'text-core.js'));
const TC = global.TB.textCore;

let pass = 0;
const failures = [];

function eq(actual, expected, label) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) { pass++; return; }
  failures.push(`${label}\n      期望 ${e}\n      实际 ${a}`);
}

/* ---------------------------------------------------------------- 手机号脱敏 */
eq(TC.maskPhone('联系 13812345678 谢谢'), '联系 138****5678 谢谢', '手机号打码：前3后4');
eq(TC.maskPhone('13812345678 和 15987654321'), '138****5678 和 159****4321', '一行多个手机号都打码');
eq(TC.maskPhone('12345678901'), '12345678901', '12 开头不是手机号，不动');
eq(TC.maskPhone('订单号202413812345678'), '订单号202413812345678', '嵌在长数字串里不误伤');
eq(TC.maskPhone('138123456789'), '138123456789', '12 位数字不是手机号');
eq(TC.maskPhone(''), '', '空串安全');
eq(TC.maskPhone(null), '', 'null 安全');

/* ---------------------------------------------------------------- 身份证脱敏 */
eq(TC.maskIdCard('身份证110101199003078515完毕'),
   '身份证1101**********8515完毕', '18 位身份证：前4后4，生日全遮');
eq(TC.maskIdCard('11010119900307851X'), '1101**********851X', '尾号 X 保留');
eq(TC.maskIdCard('110101199013078515'), '110101199013078515', '月份 13 非法，不认为是身份证');
eq(TC.maskIdCard('11010119900307851'), '11010119900307851', '17 位不动');

/* ---------------------------------------------------------------- 邮箱脱敏 */
eq(TC.maskEmail('zhang.san@qq.com'), 'zh***@qq.com', '用户名保留前2位，域名完整');
eq(TC.maskEmail('ab@x.com'), 'a***@x.com', '用户名太短只留1位');
eq(TC.maskEmail('A@b.com'), 'A***@b.com', '单字符用户名');
eq(TC.maskEmail('没有邮箱'), '没有邮箱', '无邮箱不动');

/* ---------------------------------------------------------------- 一键脱敏 */
eq(TC.maskAll('手机13812345678 身份证110101199003078515 邮箱zhangsan@qq.com'),
   '手机138****5678 身份证1101**********8515 邮箱zh***@qq.com', '三类同时打码');
eq(TC.maskAll('13812345678@qq.com'), '13***@qq.com', '邮箱里的手机号按邮箱规则，不被拆碎');

/* ---------------------------------------------------------------- 零宽字符 */
eq(TC.stripZeroWidth('a\u200Bb\u200Cc\ufeffd\u00ADe'), 'abcde', '零宽/BOM/软连字符全去');

/* ---------------------------------------------------------------- 全角半角 */
eq(TC.fullWidthToHalf('ＡＢ１２　ｃ'), 'AB12 c', '全角字母数字转半角，全角空格转空格');
eq(TC.fullWidthToHalf('中文，标点。不动！'), '中文，标点。不动！', '全角标点故意不动');

/* ---------------------------------------------------------------- 标点统一 */
eq(TC.normalizePunct('你好，世界。（测试）“引号”……'),
   '你好,世界.(测试)"引号"...', '常用中文标点转半角，省略号统一');
eq(TC.normalizePunct('单号：123；状态：完成'), '单号:123;状态:完成', '冒号分号');
eq(TC.normalizePunct(TC.fullWidthToHalf('单号：Ａ１')), '单号:A1', '组合：先转半角再统一标点');

/* ---------------------------------------------------------------- 合并断行 */
eq(TC.joinWrappedLines('exam-\nple'), 'example', '英文连字符断词拼接');
eq(TC.joinWrappedLines('今天开会\n讨论预算'), '今天开会讨论预算', '中文断行拼接');
eq(TC.joinWrappedLines('第一行。\n第二行'), '第一行。第二行', '句号结尾也算中文断行');
eq(TC.joinWrappedLines('1\n2\n3'), '1\n2\n3', '数字行不拼（可能是清单）');
eq(TC.joinWrappedLines('hello\nworld'), 'hello\nworld', '英文完整行不拼');

/* ---------------------------------------------------------------- 一键清洗 */
eq(TC.cleanPaste('　ＡＢ\u200bＣ  \n中文断\n行  '), 'ABC\n中文断行', '组合：全角+零宽+断行+首尾空白');
eq(TC.cleanPaste('a  b\t\tc'), 'a b c', '连续空格/Tab 压成一个');
eq(TC.cleanPaste('\u00A0对齐\u00A0'), '对齐', '不间断空格也能去掉');

/* ---------------------------------------------------------------- keepEdges */
eq(TC.keepEdges('abcdefgh', 2, 2), 'ab****gh', '中间打码长度不变');
eq(TC.keepEdges('abcd', 2, 2), '****', '不够保留长度时全遮');

/* ---------------------------------------------------------------- 输出 */
console.log('');
console.log(`text-core 单元测试：${pass + failures.length} 项，通过 ${pass} 项`);
if (failures.length) {
  console.error(`✗ 失败 ${failures.length} 项：`);
  for (const f of failures) console.error('  - ' + f);
  process.exit(1);
}
console.log('✓ 全部通过');
